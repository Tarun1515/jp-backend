/*==============================================================================
  jp_mdm — 037_alter_t_mdm_request_payments_manual.sql

  Three columns that turn a gateway-shaped table into a manual-first one.

  ---------------------------------------------------------------------------
  WHY THIS TABLE IS BEING ALTERED RATHER THAN REPLACED
  ---------------------------------------------------------------------------
  t_mdm_request_payments was built in 2A under a "build, don't use" note, and
  it was built for a gateway: Amount, PaymentModeId, GatewayRefNo,
  PaymentStatusId, PaidOn, and — already — VerifiedByUserId. Phase 6.5 is the
  manual path, and the manual path needs three things a gateway does not:

    Remarks       WHY the amount differs from the plan's price, when it does.
                  Required by the API when they differ (6.5-B); never by this
                  table, because the gateway caller has nobody to ask.

    PriceQuoted   The price AT REQUEST TIME. Prices are data and will change
                  (2.7); a receipt that re-derives its expected amount from
                  today's m_mdm_plans.Price would silently restate last year's
                  figure. PlanId already records WHICH plan — this records what
                  it cost when the school agreed to it.

    PaymentUid    The cross-database handle. See the next block.

  Block D of _TEMPLATE_table.sql: a deployed table is never edited in place.
  Each column has its own guard so run_all.sql stays replayable from scratch
  AND applies cleanly to an existing database.

  ---------------------------------------------------------------------------
  🔴 PaymentUid — WHY A Uid AND NOT THE PaymentId THAT ALREADY EXISTS
  ---------------------------------------------------------------------------
  Activation lives in jp_app and the payment lives here, and no query may cross
  (2.2). jp_app may legitimately STORE an id from here — t_app_subscriptions
  already holds PlanId with no FK — so a bigint would work.

  A uniqueidentifier is used because:

    1. t_app_feature_ledger.RefEntityUid is already a uniqueidentifier, and
       MONETIZATION_DESIGN names a payment as a RefEntityTypeId it expects. A
       bigint here would mean casting at the one place that must not be clever.
    2. Activation is idempotent ON this value (6.5-A). An identity column's
       value is only knowable after its INSERT; a Uid can be generated by the
       caller, which is what makes a retried verification able to ask "has this
       payment already been activated?" without first finding the row.

  ⚠️ NOT NULL with a default, and the default is load-bearing for the rows that
  already exist — of which there are none today, but a guard that only works on
  an empty table is a guard that fails the first time it matters.

  Target: SQL Server 2019 (15.0).
==============================================================================*/

USE jp_mdm;
GO

SET QUOTED_IDENTIFIER ON;
SET ANSI_NULLS ON;
GO

-- ---------------------------------------------------------------- Remarks ----
IF NOT EXISTS (SELECT 1 FROM sys.columns
               WHERE object_id = OBJECT_ID('dbo.t_mdm_request_payments') AND name = 'Remarks')
BEGIN
    PRINT '    Adding column [t_mdm_request_payments].[Remarks] ...';

    /*
      Nullable, deliberately. An exact payment needs no explanation, and
      requiring one would train admins to type "ok" — which is worse than
      NULL because it looks like information.
    */
    ALTER TABLE dbo.t_mdm_request_payments
        ADD Remarks nvarchar(500) NULL;
END
ELSE
    PRINT '    Column [t_mdm_request_payments].[Remarks] already exists — skipped.';
GO

-- ------------------------------------------------------------ PriceQuoted ----
IF NOT EXISTS (SELECT 1 FROM sys.columns
               WHERE object_id = OBJECT_ID('dbo.t_mdm_request_payments') AND name = 'PriceQuoted')
BEGIN
    PRINT '    Adding column [t_mdm_request_payments].[PriceQuoted] ...';

    /*
      decimal(10,2) — the SAME precision as m_mdm_plans.Price, which is where
      the value is copied from. Amount is decimal(18,2) and stays that way:
      what a plan costs and what somebody managed to transfer are different
      quantities, and matching the wider type here would imply they are the
      same column twice.
    */
    ALTER TABLE dbo.t_mdm_request_payments
        ADD PriceQuoted decimal(10, 2) NULL;
END
ELSE
    PRINT '    Column [t_mdm_request_payments].[PriceQuoted] already exists — skipped.';
GO

-- ------------------------------------------------------------- PaymentUid ----
IF NOT EXISTS (SELECT 1 FROM sys.columns
               WHERE object_id = OBJECT_ID('dbo.t_mdm_request_payments') AND name = 'PaymentUid')
BEGIN
    PRINT '    Adding column [t_mdm_request_payments].[PaymentUid] ...';

    ALTER TABLE dbo.t_mdm_request_payments
        ADD PaymentUid uniqueidentifier NOT NULL
            CONSTRAINT DF_t_mdm_request_payments_PaymentUid DEFAULT NEWID();
END
ELSE
    PRINT '    Column [t_mdm_request_payments].[PaymentUid] already exists — skipped.';
GO

/*
  The unique index is what makes PaymentUid usable as a cross-database key: a
  duplicate would mean two payments claiming one activation, and the activation
  side cannot see this table to notice.

  ⚠️ -I (QUOTED_IDENTIFIER ON) is mandatory for sqlcmd on any file creating a
  filtered index. This one is filtered on Is_Deleted so a soft-deleted row
  cannot block a reissue.
*/
IF NOT EXISTS (SELECT 1 FROM sys.indexes
               WHERE object_id = OBJECT_ID('dbo.t_mdm_request_payments')
                 AND name = 'UQ_t_mdm_request_payments_PaymentUid')
BEGIN
    PRINT '    Creating UQ_t_mdm_request_payments_PaymentUid ...';

    CREATE UNIQUE INDEX UQ_t_mdm_request_payments_PaymentUid
        ON dbo.t_mdm_request_payments (PaymentUid)
        WHERE Is_Deleted = 0;
END
ELSE
    PRINT '    UQ_t_mdm_request_payments_PaymentUid already exists — skipped.';
GO

/*
  An index for the admin queue: pending payments, newest first. Filtered,
  because the queue only ever asks for one status and a full-table index would
  be mostly rows nobody queues.
*/
IF NOT EXISTS (SELECT 1 FROM sys.indexes
               WHERE object_id = OBJECT_ID('dbo.t_mdm_request_payments')
                 AND name = 'IX_t_mdm_request_payments_Pending')
BEGIN
    PRINT '    Creating IX_t_mdm_request_payments_Pending ...';

    CREATE INDEX IX_t_mdm_request_payments_Pending
        ON dbo.t_mdm_request_payments (CreatedOn DESC)
        INCLUDE (RequestId, PlanId, Amount, PaymentModeId, PaymentUid)
        WHERE PaymentStatusId = 1 AND Is_Deleted = 0;
END
ELSE
    PRINT '    IX_t_mdm_request_payments_Pending already exists — skipped.';
GO

/*==============================================================================
  BUILD GUARD — the three columns and both indexes exist.

  ⚠️ This asserts SHAPE, not data. An earlier guard in this project asserted
  something about seeded rows that turned out to be a guess, and the first run
  caught it (031). The only thing true of every database that has run this file
  is the shape, so that is what is checked.
==============================================================================*/
DECLARE @missing nvarchar(400) = N'';

IF NOT EXISTS (SELECT 1 FROM sys.columns
               WHERE object_id = OBJECT_ID('dbo.t_mdm_request_payments') AND name = 'Remarks')
    SET @missing = @missing + N'Remarks ';

IF NOT EXISTS (SELECT 1 FROM sys.columns
               WHERE object_id = OBJECT_ID('dbo.t_mdm_request_payments') AND name = 'PriceQuoted')
    SET @missing = @missing + N'PriceQuoted ';

IF NOT EXISTS (SELECT 1 FROM sys.columns
               WHERE object_id = OBJECT_ID('dbo.t_mdm_request_payments') AND name = 'PaymentUid')
    SET @missing = @missing + N'PaymentUid ';

IF NOT EXISTS (SELECT 1 FROM sys.indexes
               WHERE object_id = OBJECT_ID('dbo.t_mdm_request_payments')
                 AND name = 'UQ_t_mdm_request_payments_PaymentUid')
    SET @missing = @missing + N'UQ_PaymentUid ';

IF NOT EXISTS (SELECT 1 FROM sys.indexes
               WHERE object_id = OBJECT_ID('dbo.t_mdm_request_payments')
                 AND name = 'IX_t_mdm_request_payments_Pending')
    SET @missing = @missing + N'IX_Pending ';

IF @missing <> N''
    RAISERROR('037_alter_t_mdm_request_payments_manual: missing after run: %s', 16, 1, @missing);
GO

PRINT '    t_mdm_request_payments ready for the manual path (Remarks, PriceQuoted, PaymentUid).';
GO
